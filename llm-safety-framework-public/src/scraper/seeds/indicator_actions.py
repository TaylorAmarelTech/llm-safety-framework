    """Add common fields (type, jurisdiction, title, summary) to each entry."""
    out = []
    for e in entries:
        fact = {**e, "type": "indicator_action"}
        fact["jurisdiction"] = "International"
        fact["title"] = f"{e['phase'].replace('_', ' ').title()} — {e['action'][:80]}"
        fact["summary"] = (
            f"{e['action']}. Legal justification: {e['legal_justification']}. "
            f"Red flag when: {e['red_flag_when']}."
        )
        out.append(fact)
    return out


