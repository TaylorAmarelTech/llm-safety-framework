"""
Trafficking Patterns — documented combinations of individually-legal actions
that, when stacked together, constitute trafficking or forced labor.

Each pattern references action IDs from indicator_actions.py and maps to
ILO indicators and Palermo Protocol elements.
"""

from __future__ import annotations


def _p(id, name, desc, action_ids, ilo, p_acts, p_means, purpose, risk,
       min_flag, sectors, corridors, source):
    """Build a pattern dict with all required fields."""
    return {
        "type": "trafficking_pattern", "id": id, "name": name,
        "description": desc, "action_ids": action_ids,
        "ilo_indicators": ilo,
        "palermo_acts": p_acts, "palermo_means": p_means,
        "palermo_purpose": purpose, "risk_level": risk,
        "min_actions_for_flag": min_flag,
        "sectors": sectors, "corridors": corridors,
        "source": source, "jurisdiction": "International",
        "title": name,
        "summary": f"{name}. {desc[:120]}",
    }


