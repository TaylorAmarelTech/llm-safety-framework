"""
Fine-tuning configuration generator for open-source models.

Generates ready-to-use configs for:
- Unsloth (fastest, 2x speed, 60% less memory)
- Axolotl (most flexible, supports many formats)
- HuggingFace TRL (official, SFTTrainer/DPOTrainer)
- LLaMA-Factory (simple YAML-based)

Supports model presets for popular open-source models:
- Llama 3.1/3.2 (8B, 70B)
- Mistral v0.3 / Mistral-Nemo (7B, 12B)
- Qwen 2.5 (7B, 14B, 72B)
- Gemma 2 (9B, 27B)
- Phi-3/3.5 (3.8B, 14B)
"""

from __future__ import annotations

import json
import textwrap
from enum import Enum
from pathlib import Path
from typing import Any

from pydantic import BaseModel


class FinetuneFramework(str, Enum):
    UNSLOTH = "unsloth"
    AXOLOTL = "axolotl"
    TRL = "trl"
    LLAMA_FACTORY = "llama_factory"


class ModelPreset(str, Enum):
    LLAMA_3_1_8B = "llama-3.1-8b"
    LLAMA_3_2_3B = "llama-3.2-3b"
    MISTRAL_7B_V03 = "mistral-7b-v0.3"
    MISTRAL_NEMO_12B = "mistral-nemo-12b"
    QWEN_2_5_7B = "qwen-2.5-7b"
    QWEN_2_5_14B = "qwen-2.5-14b"
    GEMMA_2_9B = "gemma-2-9b"
    PHI_3_5_MINI = "phi-3.5-mini"


# HuggingFace model IDs for each preset
MODEL_HF_IDS: dict[ModelPreset, str] = {
    ModelPreset.LLAMA_3_1_8B: "meta-llama/Llama-3.1-8B-Instruct",
    ModelPreset.LLAMA_3_2_3B: "meta-llama/Llama-3.2-3B-Instruct",
    ModelPreset.MISTRAL_7B_V03: "mistralai/Mistral-7B-Instruct-v0.3",
    ModelPreset.MISTRAL_NEMO_12B: "mistralai/Mistral-Nemo-Instruct-2407",
    ModelPreset.QWEN_2_5_7B: "Qwen/Qwen2.5-7B-Instruct",
    ModelPreset.QWEN_2_5_14B: "Qwen/Qwen2.5-14B-Instruct",
    ModelPreset.GEMMA_2_9B: "google/gemma-2-9b-it",
    ModelPreset.PHI_3_5_MINI: "microsoft/Phi-3.5-mini-instruct",
}

# LoRA target modules per architecture
LORA_TARGETS: dict[str, list[str]] = {
    "llama": ["q_proj", "k_proj", "v_proj", "o_proj", "gate_proj", "up_proj", "down_proj"],
    "mistral": ["q_proj", "k_proj", "v_proj", "o_proj", "gate_proj", "up_proj", "down_proj"],
    "qwen": ["q_proj", "k_proj", "v_proj", "o_proj", "gate_proj", "up_proj", "down_proj"],
    "gemma": ["q_proj", "k_proj", "v_proj", "o_proj", "gate_proj", "up_proj", "down_proj"],
    "phi": ["qkv_proj", "o_proj", "gate_up_proj", "down_proj"],
}


def _arch_for_preset(preset: ModelPreset) -> str:
    name = preset.value.lower()
    if "llama" in name:
        return "llama"
    if "mistral" in name:
        return "mistral"
    if "qwen" in name:
        return "qwen"
    if "gemma" in name:
        return "gemma"
    if "phi" in name:
        return "phi"
    return "llama"


class FinetuneParams(BaseModel):
    """Training hyperparameters."""
    lora_r: int = 16
    lora_alpha: int = 32
    lora_dropout: float = 0.05
    learning_rate: float = 2e-4
    num_epochs: int = 3
    batch_size: int = 4
    gradient_accumulation_steps: int = 4
    max_seq_length: int = 2048
    warmup_ratio: float = 0.03
    weight_decay: float = 0.01
    optimizer: str = "adamw_8bit"
    lr_scheduler: str = "cosine"
    bf16: bool = True
    use_4bit: bool = True
    use_gradient_checkpointing: bool = True
    save_steps: int = 100
    logging_steps: int = 10
    output_dir: str = "outputs"
    hub_model_id: str | None = None


class FinetuneConfigGenerator:
    """Generate training configs for various frameworks."""

    def __init__(
        self,
        model: ModelPreset = ModelPreset.MISTRAL_7B_V03,
        params: FinetuneParams | None = None,
    ):
        self.model = model
        self.params = params or FinetuneParams()
        self.hf_id = MODEL_HF_IDS[model]
        self.arch = _arch_for_preset(model)

    def generate_unsloth_script(
        self,
        dataset_path: str = "data/training/sft_examples.jsonl",
        objective: str = "sft",
    ) -> str:
        """Generate a complete Unsloth fine-tuning Python script.

        Args:
            dataset_path: Path to training data JSONL
            objective: 'sft' or 'dpo'
        """
        p = self.params
        targets = json.dumps(LORA_TARGETS[self.arch])

        if objective == "dpo":
            return self._unsloth_dpo_script(dataset_path, p, targets)
        return self._unsloth_sft_script(dataset_path, p, targets)

    def _unsloth_sft_script(self, dataset_path: str, p: FinetuneParams, targets: str) -> str:
        return textwrap.dedent(f'''\
            """
            Unsloth SFT fine-tuning script for LLM safety training.
            Generated by llm-safety-framework training pipeline.

            Usage:
                pip install "unsloth[colab-new] @ git+https://github.com/unslothai/unsloth.git"
                python finetune_unsloth_sft.py
            """
            from unsloth import FastLanguageModel
            from trl import SFTTrainer
            from transformers import TrainingArguments
            from datasets import load_dataset

            # Load model with 4-bit quantization
            model, tokenizer = FastLanguageModel.from_pretrained(
                model_name="{self.hf_id}",
                max_seq_length={p.max_seq_length},
                dtype=None,  # auto-detect
                load_in_4bit={p.use_4bit},
            )

            # Add LoRA adapters
            model = FastLanguageModel.get_peft_model(
                model,
                r={p.lora_r},
                lora_alpha={p.lora_alpha},
                lora_dropout={p.lora_dropout},
                target_modules={targets},
                bias="none",
                use_gradient_checkpointing="unsloth",
                random_state=42,
            )

            # Load dataset
            dataset = load_dataset("json", data_files="{dataset_path}", split="train")

            def formatting_func(examples):
                """Format messages into chat template."""
                texts = []
                for messages in examples["messages"]:
                    text = tokenizer.apply_chat_template(
                        messages, tokenize=False, add_generation_prompt=False
                    )
                    texts.append(text)
                return {{"text": texts}}

            dataset = dataset.map(formatting_func, batched=True)

            # Training
            trainer = SFTTrainer(
                model=model,
                tokenizer=tokenizer,
                train_dataset=dataset,
                dataset_text_field="text",
                max_seq_length={p.max_seq_length},
                args=TrainingArguments(
                    output_dir="{p.output_dir}",
                    num_train_epochs={p.num_epochs},
                    per_device_train_batch_size={p.batch_size},
                    gradient_accumulation_steps={p.gradient_accumulation_steps},
                    learning_rate={p.learning_rate},
                    lr_scheduler_type="{p.lr_scheduler}",
                    warmup_ratio={p.warmup_ratio},
                    weight_decay={p.weight_decay},
                    optim="{p.optimizer}",
                    bf16={p.bf16},
                    logging_steps={p.logging_steps},
                    save_steps={p.save_steps},
                    seed=42,
                ),
            )

            print("Starting SFT training...")
            trainer.train()

            # Save model
            model.save_pretrained("{p.output_dir}/final")
            tokenizer.save_pretrained("{p.output_dir}/final")

            # Export to GGUF for local inference
            model.save_pretrained_gguf(
                "{p.output_dir}/gguf", tokenizer, quantization_method="q4_k_m"
            )

            print("Training complete! Model saved to {p.output_dir}/final")
            print("GGUF exported to {p.output_dir}/gguf")
        ''')

    def _unsloth_dpo_script(self, dataset_path: str, p: FinetuneParams, targets: str) -> str:
        return textwrap.dedent(f'''\
            """
            Unsloth DPO fine-tuning script for LLM safety training.
            Trains model to prefer safe refusals over harmful responses.

            Usage:
                pip install "unsloth[colab-new] @ git+https://github.com/unslothai/unsloth.git"
                python finetune_unsloth_dpo.py
            """
            from unsloth import FastLanguageModel, PatchDPOTrainer
            PatchDPOTrainer()  # Must call before importing DPOTrainer

            from trl import DPOTrainer, DPOConfig
            from datasets import load_dataset

            # Load model
            model, tokenizer = FastLanguageModel.from_pretrained(
                model_name="{self.hf_id}",
                max_seq_length={p.max_seq_length},
                dtype=None,
                load_in_4bit={p.use_4bit},
            )

            # Add LoRA
            model = FastLanguageModel.get_peft_model(
                model,
                r={p.lora_r},
                lora_alpha={p.lora_alpha},
                lora_dropout={p.lora_dropout},
                target_modules={targets},
                bias="none",
                use_gradient_checkpointing="unsloth",
            )

            # Load DPO dataset (has prompt, chosen, rejected fields)
            dataset = load_dataset("json", data_files="{dataset_path}", split="train")

            # DPO Training
            trainer = DPOTrainer(
                model=model,
                ref_model=None,  # Unsloth handles this automatically
                tokenizer=tokenizer,
                train_dataset=dataset,
                args=DPOConfig(
                    output_dir="{p.output_dir}",
                    num_train_epochs={p.num_epochs},
                    per_device_train_batch_size={p.batch_size},
                    gradient_accumulation_steps={p.gradient_accumulation_steps},
                    learning_rate={p.learning_rate / 5},  # DPO uses lower LR
                    lr_scheduler_type="{p.lr_scheduler}",
                    warmup_ratio={p.warmup_ratio},
                    bf16={p.bf16},
                    logging_steps={p.logging_steps},
                    save_steps={p.save_steps},
                    beta=0.1,  # DPO temperature
                    max_length={p.max_seq_length},
                    max_prompt_length={p.max_seq_length // 2},
                ),
            )

            print("Starting DPO training...")
            trainer.train()
            model.save_pretrained("{p.output_dir}/final")
            tokenizer.save_pretrained("{p.output_dir}/final")
            print("DPO training complete!")
        ''')

    def generate_axolotl_config(
        self,
        dataset_path: str = "data/training/sharegpt_examples.jsonl",
    ) -> str:
        """Generate Axolotl YAML configuration."""
        p = self.params
        targets_str = "\n".join(f"  - {t}" for t in LORA_TARGETS[self.arch])

        return textwrap.dedent(f"""\
            # Axolotl config for LLM safety fine-tuning
            # Usage: accelerate launch -m axolotl.cli.train config.yml

            base_model: {self.hf_id}
            model_type: AutoModelForCausalLM
            tokenizer_type: AutoTokenizer

            load_in_4bit: {str(p.use_4bit).lower()}
            adapter: qlora
            lora_r: {p.lora_r}
            lora_alpha: {p.lora_alpha}
            lora_dropout: {p.lora_dropout}
            lora_target_modules:
            {targets_str}

            datasets:
              - path: {dataset_path}
                type: sharegpt

            sequence_len: {p.max_seq_length}
            sample_packing: true
            pad_to_sequence_len: true

            wandb_project: llm-safety-finetune
            wandb_run_id:

            output_dir: {p.output_dir}

            gradient_accumulation_steps: {p.gradient_accumulation_steps}
            micro_batch_size: {p.batch_size}
            num_epochs: {p.num_epochs}
            optimizer: {p.optimizer}
            lr_scheduler: {p.lr_scheduler}
            learning_rate: {p.learning_rate}
            warmup_ratio: {p.warmup_ratio}
            weight_decay: {p.weight_decay}

            bf16: auto
            tf32: true
            gradient_checkpointing: {str(p.use_gradient_checkpointing).lower()}

            logging_steps: {p.logging_steps}
            save_steps: {p.save_steps}
            eval_steps: {p.save_steps}

            flash_attention: true
            deepspeed:
            fsdp:
        """)

    def generate_trl_script(
        self,
        dataset_path: str = "data/training/sft_examples.jsonl",
        objective: str = "sft",
    ) -> str:
        """Generate HuggingFace TRL training script."""
        p = self.params
        targets = json.dumps(LORA_TARGETS[self.arch])

        trainer_class = "SFTTrainer" if objective == "sft" else "DPOTrainer"
        config_class = "SFTConfig" if objective == "sft" else "DPOConfig"

        return textwrap.dedent(f'''\
            """
            HuggingFace TRL {objective.upper()} training script.
            Usage: python finetune_trl.py
            Requires: pip install trl peft bitsandbytes accelerate
            """
            import torch
            from transformers import AutoModelForCausalLM, AutoTokenizer, BitsAndBytesConfig
            from peft import LoraConfig, get_peft_model, prepare_model_for_kbit_training
            from trl import {trainer_class}, {config_class}
            from datasets import load_dataset

            # Quantization config
            bnb_config = BitsAndBytesConfig(
                load_in_4bit={p.use_4bit},
                bnb_4bit_quant_type="nf4",
                bnb_4bit_compute_dtype=torch.bfloat16,
                bnb_4bit_use_double_quant=True,
            )

            # Load model
            model = AutoModelForCausalLM.from_pretrained(
                "{self.hf_id}",
                quantization_config=bnb_config,
                device_map="auto",
                trust_remote_code=True,
            )
            tokenizer = AutoTokenizer.from_pretrained("{self.hf_id}", trust_remote_code=True)
            tokenizer.pad_token = tokenizer.eos_token

            # LoRA config
            peft_config = LoraConfig(
                r={p.lora_r},
                lora_alpha={p.lora_alpha},
                lora_dropout={p.lora_dropout},
                target_modules={targets},
                bias="none",
                task_type="CAUSAL_LM",
            )

            model = prepare_model_for_kbit_training(model)
            model = get_peft_model(model, peft_config)
            model.print_trainable_parameters()

            # Load dataset
            dataset = load_dataset("json", data_files="{dataset_path}", split="train")

            # Train
            trainer = {trainer_class}(
                model=model,
                tokenizer=tokenizer,
                train_dataset=dataset,
                args={config_class}(
                    output_dir="{p.output_dir}",
                    num_train_epochs={p.num_epochs},
                    per_device_train_batch_size={p.batch_size},
                    gradient_accumulation_steps={p.gradient_accumulation_steps},
                    learning_rate={p.learning_rate},
                    lr_scheduler_type="{p.lr_scheduler}",
                    warmup_ratio={p.warmup_ratio},
                    weight_decay={p.weight_decay},
                    bf16={p.bf16},
                    logging_steps={p.logging_steps},
                    save_steps={p.save_steps},
                    max_seq_length={p.max_seq_length},
                ),
            )

            trainer.train()
            trainer.save_model("{p.output_dir}/final")
            print("Training complete!")
        ''')

    def generate_llama_factory_config(
        self,
        dataset_path: str = "data/training/alpaca_examples.jsonl",
    ) -> str:
        """Generate LLaMA-Factory YAML config."""
        p = self.params
        targets = ",".join(LORA_TARGETS[self.arch])

        return textwrap.dedent(f"""\
            # LLaMA-Factory config for safety fine-tuning
            # Usage: llamafactory-cli train config.yaml

            ### Model
            model_name_or_path: {self.hf_id}
            trust_remote_code: true

            ### Method
            stage: sft
            do_train: true
            finetuning_type: lora
            lora_rank: {p.lora_r}
            lora_alpha: {p.lora_alpha}
            lora_dropout: {p.lora_dropout}
            lora_target: {targets}
            quantization_bit: 4

            ### Dataset
            dataset: safety_training
            dataset_dir: {str(Path(dataset_path).parent)}
            template: default
            cutoff_len: {p.max_seq_length}

            ### Output
            output_dir: {p.output_dir}
            logging_steps: {p.logging_steps}
            save_steps: {p.save_steps}
            overwrite_output_dir: true

            ### Train
            per_device_train_batch_size: {p.batch_size}
            gradient_accumulation_steps: {p.gradient_accumulation_steps}
            learning_rate: {p.learning_rate}
            num_train_epochs: {p.num_epochs}
            lr_scheduler_type: {p.lr_scheduler}
            warmup_ratio: {p.warmup_ratio}
            bf16: true
            optim: {p.optimizer}
        """)

    def generate_config(
        self,
        framework: FinetuneFramework,
        dataset_path: str = "data/training/sft_examples.jsonl",
        objective: str = "sft",
    ) -> str:
        """Generate config for the specified framework."""
        generators = {
            FinetuneFramework.UNSLOTH: lambda: self.generate_unsloth_script(dataset_path, objective),
            FinetuneFramework.AXOLOTL: lambda: self.generate_axolotl_config(dataset_path),
            FinetuneFramework.TRL: lambda: self.generate_trl_script(dataset_path, objective),
            FinetuneFramework.LLAMA_FACTORY: lambda: self.generate_llama_factory_config(dataset_path),
        }
        return generators[framework]()

    def generate_all_configs(
        self,
        output_dir: Path = Path("configs/finetune"),
        dataset_path: str = "data/training/sft_examples.jsonl",
    ) -> dict[str, Path]:
        """Generate configs for all frameworks, saving to files."""
        output_dir.mkdir(parents=True, exist_ok=True)
        results = {}

        # Unsloth SFT
        path = output_dir / "finetune_unsloth_sft.py"
        path.write_text(self.generate_unsloth_script(dataset_path, "sft"))
        results["unsloth_sft"] = path

        # Unsloth DPO
        dpo_path = dataset_path.replace("sft_examples", "dpo_pairs")
        path = output_dir / "finetune_unsloth_dpo.py"
        path.write_text(self.generate_unsloth_script(dpo_path, "dpo"))
        results["unsloth_dpo"] = path

        # Axolotl
        sg_path = dataset_path.replace("sft_examples", "sharegpt_examples")
        path = output_dir / "axolotl_config.yml"
        path.write_text(self.generate_axolotl_config(sg_path))
        results["axolotl"] = path

        # TRL
        path = output_dir / "finetune_trl.py"
        path.write_text(self.generate_trl_script(dataset_path, "sft"))
        results["trl"] = path

        # LLaMA-Factory
        alp_path = dataset_path.replace("sft_examples", "alpaca_examples")
        path = output_dir / "llama_factory_config.yml"
        path.write_text(self.generate_llama_factory_config(alp_path))
        results["llama_factory"] = path

        return results

    def get_requirements(self, framework: FinetuneFramework) -> list[str]:
        """Get pip requirements for a framework."""
        base = ["torch>=2.1", "transformers>=4.40", "datasets", "accelerate"]
        extras = {
            FinetuneFramework.UNSLOTH: [
                "unsloth[colab-new] @ git+https://github.com/unslothai/unsloth.git",
                "trl>=0.8",
                "bitsandbytes",
            ],
            FinetuneFramework.AXOLOTL: [
                "axolotl @ git+https://github.com/OpenAccess-AI-Collective/axolotl.git",
                "flash-attn",
                "deepspeed",
            ],
            FinetuneFramework.TRL: [
                "trl>=0.8",
                "peft>=0.10",
                "bitsandbytes",
            ],
            FinetuneFramework.LLAMA_FACTORY: [
                "llamafactory @ git+https://github.com/hiyouga/LLaMA-Factory.git",
            ],
        }
        return base + extras.get(framework, [])
