"""
Research Agent System - Independent Specialized Agents

Each agent is self-contained, domain-focused, and can run independently.
They share a common protocol (BaseResearchAgent) and output format but
have no dependencies on each other.

Agents:
    1. EnforcementAgent           - SEC/DOJ/FinCEN/FATF/IRS enforcement actions
    2. CrossPollinationAgent      - Cross-domain pattern transfer
    3. TechniqueEvolutionAgent    - Emerging techniques (AI, DeFi, prompt injection)
    4. CoverageGapAgent           - Test suite gap analysis and filling
    5. EthicsBoundaryAgent        - Dual-use, usury, ethical edge cases
    6. FinancialCrimeAgent        - Tax evasion, AML, white collar deep-dive
    7. JurisdictionAgent          - Jurisdiction-specific regulations and loopholes
    8. EmbeddingResearchAgent     - Novel embedding/vector attack technique discovery
    9. GitHubLibraryAgent         - Adversarial ML repo discovery and evaluation
   10. ModelBenchmarkAgent        - Embedding model tracking and attack surface eval
   11. TechniqueIntegrationAgent  - Convert findings into implementation plans
   12. AttackSurfaceEvolutionAgent - Monitor attack/defense co-evolution
"""

from __future__ import annotations

import json
import hashlib
import logging
import os
from abc import ABC, abstractmethod
from dataclasses import dataclass, field, asdict
from datetime import datetime, timezone
from enum import Enum
from pathlib import Path
from typing import Any, Optional

logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# Shared data types
# ---------------------------------------------------------------------------

class Severity(str, Enum):
    """How severe/dangerous the discovered pattern is."""
    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"
    CRITICAL = "critical"


class Domain(str, Enum):
    """Research domains covered by the framework."""
    TRAFFICKING = "trafficking"
    TAX_EVASION = "tax_evasion"
    MONEY_LAUNDERING = "money_laundering"
    WHITE_COLLAR_CRIME = "white_collar_crime"
    FINANCIAL_CRIME = "financial_crime"  # umbrella
    PROMPT_INJECTION = "prompt_injection"
    ETHICS = "ethics"
    CROSS_DOMAIN = "cross_domain"


@dataclass
class Finding:
    """A single research finding from any agent."""
    id: str
    agent_name: str
    domain: str
    title: str
    description: str
    severity: str = "medium"
    source: str = ""
    tags: list[str] = field(default_factory=list)
    related_corridors: list[str] = field(default_factory=list)
    related_indicators: list[str] = field(default_factory=list)
    confidence: float = 0.8
    discovered_at: str = field(default_factory=lambda: datetime.now(tz=timezone.utc).isoformat())
    metadata: dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass
class GeneratedTest:
    """A test case generated by a research agent."""
    id: str
    agent_name: str
    prompt: str
    category: str
    domain: str
    difficulty: str = "hard"
    corridor: str = ""
    ilo_indicators: list[str] = field(default_factory=list)
    attack_type: str = "information_seeking"
    expected_refusal: bool = True
    rationale: str = ""
    source_finding_id: str = ""
    created_at: str = field(default_factory=lambda: datetime.now(tz=timezone.utc).isoformat())

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass
class ResearchReport:
    """Output from a single agent run."""
    agent_name: str
    domain: str
    findings: list[Finding]
    generated_tests: list[GeneratedTest]
    summary: str
    run_duration_seconds: float = 0.0
    llm_calls_made: int = 0
    tokens_used: int = 0
    started_at: str = field(default_factory=lambda: datetime.now(tz=timezone.utc).isoformat())
    completed_at: str = ""
    error: Optional[str] = None

    def to_dict(self) -> dict[str, Any]:
        return {
            "agent_name": self.agent_name,
            "domain": self.domain,
            "findings": [f.to_dict() for f in self.findings],
            "generated_tests": [t.to_dict() for t in self.generated_tests],
            "summary": self.summary,
            "run_duration_seconds": self.run_duration_seconds,
            "llm_calls_made": self.llm_calls_made,
            "tokens_used": self.tokens_used,
            "started_at": self.started_at,
            "completed_at": self.completed_at,
            "error": self.error,
        }


# ---------------------------------------------------------------------------
# Base agent protocol
# ---------------------------------------------------------------------------

class BaseResearchAgent(ABC):
    """
    Protocol for all research agents.

    Each agent:
    - Focuses on a single domain/concern
    - Can run independently (no inter-agent dependencies)
    - Uses LLM API via the shared _call_llm() helper
    - Outputs Finding and GeneratedTest objects
    - Persists results to data/research/{agent_name}/
    """

    NAME: str = "base"
    DOMAIN: str = "general"
    DESCRIPTION: str = ""

    def __init__(
        self,
        data_dir: str | Path = "data/research",
        endpoint: Optional[dict[str, Any]] = None,
        model_id: Optional[str] = None,
    ):
        self.data_dir = Path(data_dir) / self.NAME
        self.data_dir.mkdir(parents=True, exist_ok=True)
        self.endpoint = endpoint
        self.model_id = model_id
        self._client = None
        self._call_count = 0
        self._token_count = 0

    # ----- LLM helper -----

    async def _call_llm(
        self,
        prompt: str,
        system: str = "",
        temperature: float = 0.7,
        max_tokens: int = 4000,
    ) -> str:
        """Call the LLM via UnifiedAPIClient. Lazy-inits the client."""
        if self._client is None:
            if self.endpoint is None:
                raise ValueError(
                    f"{self.NAME}: No endpoint configured. Pass endpoint dict or set via coordinator."
                )
            from src.api_client import UnifiedAPIClient
            self._client = UnifiedAPIClient(self.endpoint)

        messages = [{"role": "user", "content": prompt}]
        result = await self._client.chat(
            model_id=self.model_id or self.endpoint.get("default_model", ""),
            messages=messages,
            temperature=temperature,
            max_tokens=max_tokens,
            system_prompt=system or None,
        )
        self._call_count += 1
        return result

    def _parse_json_response(self, text: str) -> dict[str, Any]:
        """Extract JSON from LLM response text."""
        # Try ```json blocks first
        if "```json" in text:
            start = text.find("```json") + 7
            end = text.find("```", start)
            if end > start:
                try:
                    return json.loads(text[start:end].strip())
                except json.JSONDecodeError:
                    pass

        # Try raw JSON object
        if "{" in text:
            start = text.find("{")
            end = text.rfind("}") + 1
            try:
                return json.loads(text[start:end])
            except json.JSONDecodeError:
                pass

        # Try JSON array
        if "[" in text:
            start = text.find("[")
            end = text.rfind("]") + 1
            try:
                return {"items": json.loads(text[start:end])}
            except json.JSONDecodeError:
                pass

        return {"raw": text[:2000]}

    def _make_id(self, prefix: str, text: str) -> str:
        """Generate a deterministic ID from text."""
        h = hashlib.md5(text.encode()).hexdigest()[:8]
        return f"{prefix}_{h}"

    # ----- Persistence -----

    def save_report(self, report: ResearchReport) -> Path:
        """Save a research report to disk."""
        ts = datetime.now(tz=timezone.utc).strftime("%Y%m%d_%H%M%S")
        path = self.data_dir / f"report_{ts}.json"
        path.write_text(json.dumps(report.to_dict(), indent=2), encoding="utf-8")
        logger.info(f"{self.NAME}: Saved report to {path}")
        return path

    def load_previous_findings(self) -> list[Finding]:
        """Load findings from previous runs to avoid duplication."""
        findings = []
        for f in sorted(self.data_dir.glob("report_*.json")):
            try:
                data = json.loads(f.read_text(encoding="utf-8"))
                for fd in data.get("findings", []):
                    findings.append(Finding(**fd))
            except Exception:
                continue
        return findings

    # ----- Abstract interface -----

    @abstractmethod
    async def run(self, **kwargs) -> ResearchReport:
        """
        Execute the agent's research cycle.

        Returns a ResearchReport with findings and generated tests.
        """
        ...

    @abstractmethod
    def get_system_prompt(self) -> str:
        """Return the system prompt for this agent's LLM calls."""
        ...


# ---------------------------------------------------------------------------
# Agent registry
# ---------------------------------------------------------------------------

_AGENT_REGISTRY: dict[str, type[BaseResearchAgent]] = {}


def register_agent(cls: type[BaseResearchAgent]) -> type[BaseResearchAgent]:
    """Decorator to register a research agent class."""
    _AGENT_REGISTRY[cls.NAME] = cls
    return cls


def get_agent(name: str) -> type[BaseResearchAgent]:
    """Get an agent class by name."""
    if name not in _AGENT_REGISTRY:
        raise KeyError(f"Unknown agent: {name}. Available: {list(_AGENT_REGISTRY)}")
    return _AGENT_REGISTRY[name]


def list_agents() -> dict[str, str]:
    """Return {name: description} for all registered agents."""
    return {name: cls.DESCRIPTION for name, cls in _AGENT_REGISTRY.items()}
