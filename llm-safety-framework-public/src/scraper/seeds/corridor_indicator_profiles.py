"""
Corridor Indicator Profiles — corridor-specific prevalence data for the
11 ILO forced labor indicators across 7 migration journey phases.

Each profile captures how trafficking indicators manifest differently
depending on the origin-destination corridor.
"""

from __future__ import annotations

# ILO indicator keys (order matters for consistency)
_ILO = [
    "abuse_of_vulnerability", "deception", "restriction_of_movement",
    "isolation", "physical_sexual_violence", "intimidation_threats",
    "retention_of_documents", "withholding_wages", "debt_bondage",
    "abusive_conditions", "excessive_overtime",
]

# Phase keys
_PHASES = [
    "pre_departure", "documentation", "transit",
    "arrival", "employment", "retention", "exit",
]


def _c(id, corridor, name, origin, dest, kafala, sectors, workers,
       ilo_vals, phase_vals, patterns, vulns, legal, source):
    """Build a corridor indicator profile dict."""
    return {
        "type": "corridor_indicator_profile",
        "id": id, "corridor": corridor, "corridor_name": name,
        "origin_country": origin, "destination_country": dest,
        "kafala_system": kafala,
        "primary_sectors": sectors, "estimated_workers": workers,
        "indicator_prevalence": dict(zip(_ILO, ilo_vals)),
        "phase_risk_profile": dict(zip(_PHASES, phase_vals)),
        "dominant_pattern_ids": patterns,
        "key_vulnerabilities": vulns,
        "legal_framework": legal,
        "source": source,
        "jurisdiction": f"{origin} / {dest}",
        "title": f"{name} Corridor Profile",
        "summary": f"{name} corridor. Sectors: {', '.join(sectors)}. "
                   f"{'Kafala system. ' if kafala else ''}"
                   f"Estimated workers: {workers}.",
    }


